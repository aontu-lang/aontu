func TestModArguments(t *testing.T) {
	if out, _, code := modRun("--help"); 0 != code ||
		!strings.Contains(out, "aontu mod") {
		t.Fatalf("--help = %d:\n%s", code, out)
	}
	for _, args := range [][]string{{}, {"nope"}, {"tidy", "a", "b"}} {
		if _, errw, code := modRun(args...); 2 != code ||
			!strings.Contains(errw, "needs tidy, verify, vendor or manifest") {
			t.Fatalf("%v = %d: %s", args, code, errw)
		}
	}
	if _, errw, code := modRun("--format", "yaml", "tidy"); 2 != code ||
		!strings.Contains(errw, "text or json") {
		t.Fatalf("bad format = %d: %s", code, errw)
	}
	if _, errw, code := modRun("--format"); 2 != code ||
		!strings.Contains(errw, "text or json") {
		t.Fatalf("missing format value = %d: %s", code, errw)
	}
	if _, errw, code := modRun("--nope", "tidy"); 2 != code ||
		!strings.Contains(errw, "unknown mod option") {
		t.Fatalf("bad option = %d: %s", code, errw)
	}
	// `--against` gates a manifest and means nothing to the other two;
	// accepting it there would say it had been honoured.
	if _, errw, code := modRun("tidy", "--against", "x"); 2 != code ||
		!strings.Contains(errw, "--against is a manifest option") {
		t.Fatalf("against on tidy = %d: %s", code, errw)
	}
	if _, errw, code := modRun("manifest", "--against"); 2 != code ||
		!strings.Contains(errw, "--against needs a module directory") {
		t.Fatalf("missing against value = %d: %s", code, errw)
	}
}

// The command's own manifest surface: the text body, the JSON envelope
// and the exit classes. What the report SAYS is proved against the
// package API in go/modtool_test.go, with ts/test/mod.test.ts as the
// cross-port twin.
func TestModManifestCommand(t *testing.T) {
	pub := func(version, src string) string {
		dir := t.TempDir()
		decl := "mod: {path: \"corp.example/schemas/service\""
		if "" != version {
			decl += ", version: \"" + version + "\""
		}
		decl += ", main: \"service.aon\"}\n"
		modWrite(t, filepath.Join(dir, "mod.aon"), decl)
		if "" != src {
			modWrite(t, filepath.Join(dir, "service.aon"), src)
		}
		return dir
	}

	out, _, code := modRun("manifest", pub("1.1.0", modToolSource))
	if 0 != code {
		t.Fatalf("manifest = %d:\n%s", code, out)
	}
	for _, want := range []string{
		"verdict: ok",
		"corp.example/schemas/service@1 1.1.0",
		"config: " + aontu.ModuleConfigMediaType,
		aontu.ModuleAnnotationCanon + ": aon1-",
		"layer: service.aon",
	} {
		if !strings.Contains(out, want) {
			t.Fatalf("manifest text lacks %q:\n%s", want, out)
		}
	}

	// A module that declares no version has nothing to publish under,
	// and that is an error class rather than a missing fetch.
	miss, _, code := modRun("manifest", pub("", modToolSource))
	if 4 != code || !strings.Contains(miss, "mod.version: missing") {
		t.Fatalf("no version = %d:\n%s", code, miss)
	}

	// The gate's exit class is Subsume's, because the gate IS a
	// subsumption check.
	prior := pub("1.0.0", modToolSource)
	next := pub("1.1.0", modToolSource+"region: *\"eu\" | string\n")
	gated, _, code := modRun("manifest", "--against", prior, next)
	if 1 != code || !strings.Contains(gated, "verdict: breaking") {
		t.Fatalf("gate = %d:\n%s", code, gated)
	}

	// Subsumption is THREE-valued plus error, and every value has its
	// own exit class: a question the checker cannot decide is not a
	// pass, and a caller reading exit codes can tell the two apart.
	undecided, _, code := modRun("manifest",
		"--against", pub("1.0.0", "a: min(1)\n"),
		pub("1.1.0", "a: must(min(1), \"m\")\n"))
	if 3 != code || !strings.Contains(undecided, "verdict: undecided") {
		t.Fatalf("undecided gate = %d:\n%s", code, undecided)
	}

	jsonOut, _, code := modRun("manifest", "--format", "json",
		pub("1.1.0", modToolSource))
	if 0 != code {
		t.Fatalf("manifest json = %d:\n%s", code, jsonOut)
	}
	var report struct {
		Aontu struct {
			Verb string `json:"verb"`
		} `json:"aontu"`
		Annotations map[string]string `json:"annotations"`
		Verdict     string            `json:"verdict"`
	}
	if err := json.Unmarshal([]byte(jsonOut), &report); nil != err {
		t.Fatalf("json: %v\n%s", err, jsonOut)
	}
	if "mod manifest" != report.Aontu.Verb || "ok" != report.Verdict ||
		!strings.HasPrefix(report.Annotations[aontu.ModuleAnnotationCanon],
			"aon1-") {
		t.Fatalf("report %+v", report)
	}
}

func TestModTidyJSONIsTheReport(t *testing.T) {
	dir := modProject(t, "\"corp.example/schemas/service@1\": {v: \"1.4.2\"}")
	modVendorTree(t, dir, "corp.example/schemas/service@1", map[string]string{
		"mod.aon":     "mod: {path: \"corp.example/schemas/service\", main: \"service.aon\"}\n",
		"service.aon": modToolSource,
	})

	out, _, code := modRun("tidy", "--format", "json", dir)
	if 0 != code {
		t.Fatalf("tidy json = %d:\n%s", code, out)
	}
	var report struct {
		Aontu struct {
			Verb string `json:"verb"`
		} `json:"aontu"`
		Lock []struct {
			Mod string `json:"mod"`
		} `json:"lock"`
		Missing []string `json:"missing"`
		Verdict string   `json:"verdict"`
	}
	if err := json.Unmarshal([]byte(out), &report); nil != err {
		t.Fatalf("not JSON: %v\n%s", err, out)
	}
	if "mod tidy" != report.Aontu.Verb || "ok" != report.Verdict ||
		1 != len(report.Lock) ||
		"corp.example/schemas/service@1" != report.Lock[0].Mod {
		t.Fatalf("bad report: %+v", report)
	}
}

// THE VERIFY VERB (the review's finding H, use-cases/BUGS.md §32): a
// gate that answers whether the stores still mean what the lockfile
// pins, and changes nothing. Tidy cannot be that gate -- it recomputes
// and rewrites by design, so it makes the lockfile agree with whatever
// the store now holds, tampering included. The TypeScript twin is
// `verify-catches-a-tampered-store-and-changes-nothing`.
func TestModVerifyCommand(t *testing.T) {
	dir := modProject(t, "\"corp.example/schemas/service@1\": {v: \"1.4.2\"}")
	modVendorTree(t, dir, "corp.example/schemas/service@1", map[string]string{
		"mod.aon": "mod: {path: \"corp.example/schemas/service\"," +
			" main: \"service.aon\"}\n",
		"service.aon": modToolSource,
	})
	// Before the lockfile exists there is nothing to check, which is a
	// refusal and not a pass: the repair is a tidy, and the line says so
	// rather than sending the reader to a fetch.
	if out, _, code := modRun("verify", dir); 1 != code ||
		!strings.Contains(out, "verdict: unlocked") ||
		!strings.Contains(out,
			"corp.example/schemas/service@1: not in the lockfile (run: aontu mod tidy)") {
		t.Fatalf("unlocked verify = %d: %s", code, out)
	}

	if _, errw, code := modRun("tidy", dir); 0 != code {
		t.Fatalf("tidy = %d: %s", code, errw)
	}
	lock, err := os.ReadFile(filepath.Join(dir, "mod-lock.aon"))
	if nil != err {
		t.Fatal(err)
	}

	out, errw, code := modRun("verify", dir)
	if 0 != code || !strings.Contains(out, ": verified") {
		t.Fatalf("clean verify = %d: %s%s", code, out, errw)
	}

	svc := filepath.Join(dir, "aon_vendor", "corp.example", "schemas",
		"service@1", "service.aon")
	modWrite(t, svc, strings.Replace(modToolSource, "8080", "9090", 1))

	out, _, code = modRun("verify", dir)
	if 1 != code || !strings.Contains(out, "verdict: mismatch") ||
		!strings.Contains(out, "but the store means") {
		t.Fatalf("tampered verify = %d: %s", code, out)
	}
	// THE LOCKFILE IS UNTOUCHED, which is the whole difference from
	// tidy: a gate that rewrote what it was checking would pass every
	// time.
	now, err := os.ReadFile(filepath.Join(dir, "mod-lock.aon"))
	if nil != err || string(lock) != string(now) {
		t.Fatal("verify rewrote the lockfile")
	}

	// A module that no longer stands up says so, rather than reporting
	// the hash of nil as though it were a meaning.
	modWrite(t, svc, "a: 1\na: 2\n")
	if out, _, code = modRun("verify", dir); 1 != code ||
		!strings.Contains(out, "it does not evaluate") {
		t.Fatalf("broken verify = %d: %s", code, out)
	}

	// And TIDY refuses to pin it, rather than writing the hash of nil.
	if out, _, code = modRun("tidy", dir); 4 != code ||
		!strings.Contains(out, "does not evaluate on its own; nothing to pin") {
		t.Fatalf("tidy over a broken module = %d: %s", code, out)
	}
}
