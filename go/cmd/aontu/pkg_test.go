func TestPkgVendorMaterialisesTheClosure(t *testing.T) {
	// From the CACHE, keyed by the hash the lockfile pins and the
	// package path: that is what content-addressed means, and why
	// `vendor` needs a lockfile while `tidy` needs a store.
	dir := pkgProject(t, "")
	v, _ := aontu.New().Unify(pkgToolSource)
	hash := aontu.CanonHash(v)

	xdg := filepath.Join(dir, "xdg")
	cachedir := filepath.Join(xdg, "aontu", "pkg", "store", hash, "corp.example", "schemas", "service")
	pkgWrite(t, filepath.Join(cachedir, "pkg.aontu"), pkgServiceFiles["pkg.aontu"])
	pkgWrite(t, filepath.Join(cachedir, "service.aontu"), pkgToolSource)
	pkgWrite(t, filepath.Join(dir, "aontu_meta", "pkg-lock.aontu"),
		"# pkg-lock.aontu (generated by `aontu sync`; do not edit)\n"+
			"{\"lock\":{\"corp.example/schemas/service\":{\"archive\":\"\",\"canon\":\""+hash+
			"\",\"v\":\"1.4.2\"}}}\n")

	t.Setenv("XDG_CACHE_HOME", xdg)
	out, errw, code := pkgRun("vendor", dir)
	if 0 != code {
		t.Fatalf("vendor = %d: %s\n%s", code, errw, out)
	}
	if _, err := os.Stat(filepath.Join(dir, "aontu_meta", "vendor", "corp.example",
		"schemas", "service", "service.aontu")); nil != err {
		t.Fatalf("want the package materialised: %v", err)
	}
}

