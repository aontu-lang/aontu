func TestPkgVerifyCommand(t *testing.T) {
	dir := pkgProject(t, "\"corp.example/schemas/service\": {v: \"1.4.2\"}")
	pkgVendorTree(t, dir, "corp.example/schemas/service", pkgServiceFiles)
	// Before the lockfile exists there is nothing to check, which is a
	// refusal and not a pass: the repair is a sync, and the line says so.
	if out, _, code := pkgRun("verify", dir); 1 != code ||
		!strings.Contains(out, "verdict: unlocked") ||
		!strings.Contains(out,
			"corp.example/schemas/service: not in the lockfile (run: aontu sync)") {
		t.Fatalf("unlocked verify = %d: %s", code, out)
	}

	if _, errw, code := pkgRun("tidy", dir); 0 != code {
		t.Fatalf("tidy = %d: %s", code, errw)
	}
	lock, err := os.ReadFile(filepath.Join(dir, "aontu_meta", "pkg-lock.aontu"))
	if nil != err {
		t.Fatal(err)
	}

	out, errw, code := pkgRun("verify", dir)
	if 0 != code || !strings.Contains(out, ": verified") {
		t.Fatalf("clean verify = %d: %s%s", code, out, errw)
	}

	svc := filepath.Join(dir, "aontu_meta", "vendor", "corp.example", "schemas",
		"service", "service.aontu")
	pkgWrite(t, svc, strings.Replace(pkgToolSource, "8080", "9090", 1))

	// BYTES BEFORE MEANING: the archive pin is what moves first.
	out, _, code = pkgRun("verify", dir)
	if 1 != code || !strings.Contains(out, "verdict: mismatch") ||
		!strings.Contains(out, "pinned archive sha256:") ||
		!strings.Contains(out, "but the store holds sha256:") {
		t.Fatalf("tampered verify = %d: %s", code, out)
	}
	now, err := os.ReadFile(filepath.Join(dir, "aontu_meta", "pkg-lock.aontu"))
	if nil != err || string(lock) != string(now) {
		t.Fatal("verify rewrote the lockfile")
	}

	// With the archive pin made to agree, the meaning is what is judged.
	repin := func(src string) {
		pkgWrite(t, svc, src)
		arch := aontu.ArchiveOf(filepath.Dir(svc)).Digest
		i := strings.Index(string(lock), "\"archive\":\"")
		j := strings.Index(string(lock)[i+11:], "\"")
		pkgWrite(t, filepath.Join(dir, "aontu_meta", "pkg-lock.aontu"),
			string(lock)[:i+11]+arch+string(lock)[i+11+j:])
	}
	repin("a: 1\na: 2\n")
	if out, _, code = pkgRun("verify", dir); 1 != code ||
		!strings.Contains(out, "it does not evaluate") {
		t.Fatalf("broken verify = %d: %s", code, out)
	}
	repin(strings.Replace(pkgToolSource, "8080", "9090", 1))
	if out, _, code = pkgRun("verify", dir); 1 != code ||
		!strings.Contains(out, "but the store means aon1-") {
		t.Fatalf("moved verify = %d: %s", code, out)
	}

	// A kept manifest is a pin of its own.
	repin(pkgToolSource)
	tree := filepath.Dir(svc)
	a := aontu.ArchiveOf(tree)
	pkgWrite(t, filepath.Join(tree, "aontu_meta", "manifest.aontu"),
		"{\"archive\":{\"digest\":\""+a.Digest+"\",\"files\":[{\"path\":\"pkg.aontu\",\"digest\":\"sha256:0\",\"size\":1}]}}")
	if _, _, code := pkgRun("tidy", dir); 0 != code {
		t.Fatal("retidy")
	}
	if out, _, code = pkgRun("verify", dir); 1 != code ||
		!strings.Contains(out, "pinned manifest") {
		t.Fatalf("manifest verify = %d: %s", code, out)
	}

	// And TIDY refuses to pin a broken module, rather than writing the
	// hash of nil.
	pkgWrite(t, svc, "a: 1\na: 2\n")
	if out, _, code = pkgRun("tidy", dir); 4 != code ||
		!strings.Contains(out, "does not evaluate on its own; nothing to pin") {
		t.Fatalf("tidy over a broken module = %d: %s", code, out)
	}
}

