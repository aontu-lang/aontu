func TestPkgArguments(t *testing.T) {
	if out, _, code := pkgRun("--help"); 0 != code ||
		!strings.Contains(out, "aontu pkg") {
		t.Fatalf("--help = %d:\n%s", code, out)
	}
	for _, args := range [][]string{{}, {"nope"}, {"tidy", "a", "b"}} {
		if _, errw, code := pkgRun(args...); 2 != code ||
			!strings.Contains(errw, "pkg needs one of tidy, verify") {
			t.Fatalf("%v = %d: %s", args, code, errw)
		}
	}
	if _, errw, code := pkgRun("--format", "yaml", "tidy"); 2 != code ||
		!strings.Contains(errw, "text or json") {
		t.Fatalf("bad format = %d: %s", code, errw)
	}
	if _, errw, code := pkgRun("--format"); 2 != code ||
		!strings.Contains(errw, "text or json") {
		t.Fatalf("missing format value = %d: %s", code, errw)
	}
	if _, errw, code := pkgRun("--nope", "tidy"); 2 != code ||
		!strings.Contains(errw, "unknown pkg option") {
		t.Fatalf("bad option = %d: %s", code, errw)
	}
	for _, flag := range []string{"--to", "--base", "--key", "--token", "--write",
		"--listen", "--upstream"} {
		if _, errw, code := pkgRun("tidy", flag); 2 != code ||
			!strings.Contains(errw, flag+" needs a value") {
			t.Fatalf("%s = %d: %s", flag, code, errw)
		}
	}
	// Every option the table knows parses, whatever the subcommand
	// does with it.
	if _, _, code := pkgRun("--frozen", "--yes", "--to", "x", "--key", "k",
		"--token", "t", "--write", "w", "--listen", "l", "--base", "b",
		"--upstream", "u", "tree", t.TempDir()); 0 != code {
		t.Fatalf("the option table = %d", code)
	}
	// A verb that reads a document takes the trust options.
	for _, flag := range [][]string{{"--trust", "none"}, {"--include-root", "."},
		{"--text-ext", "md"}} {
		args := append(append([]string{}, flag...), "tidy")
		if _, errw, code := pkgRun(args...); 2 == code &&
			strings.Contains(errw, "unknown pkg option") {
			t.Fatalf("%v refused: %s", flag, errw)
		}
	}
	if _, errw, code := pkgRun("--trust", "everything", "tidy"); 2 != code ||
		!strings.Contains(errw, "--trust needs") {
		t.Fatalf("bad trust = %d: %s", code, errw)
	}
	// `--against` gates a manifest and means nothing to the others;
	// accepting it there would say it had been honoured.
	if _, errw, code := pkgRun("tidy", "--against", "x"); 2 != code ||
		!strings.Contains(errw, "--against is a manifest option") {
		t.Fatalf("against on tidy = %d: %s", code, errw)
	}
	if _, errw, code := pkgRun("manifest", "--against"); 2 != code ||
		!strings.Contains(errw, "--against needs a value") {
		t.Fatalf("missing against value = %d: %s", code, errw)
	}
}

// The command's own manifest surface: the text body, the JSON envelope
// and the exit classes. What the report SAYS is proved against the
// package API in go/pkg_test.go, with ts/test/pkg.test.ts as the
// cross-port twin.
func TestPkgManifestCommand(t *testing.T) {
	pub := func(version, src string, extra string) string {
		dir := t.TempDir()
		decl := "pkg: {path: \"corp.example/schemas/service\""
		if "" != version {
			decl += ", version: \"" + version + "\""
		}
		decl += ", main: \"service.aontu\"}\npublish: public\n" + extra
		pkgWrite(t, filepath.Join(dir, "pkg.aontu"), decl)
		if "" != src {
			pkgWrite(t, filepath.Join(dir, "service.aontu"), src)
		}
		return dir
	}

	out, _, code := pkgRun("manifest", pub("1.1.0", pkgToolSource,
		"dep: {\"alias:old\": {pkg: \"corp.example/core\", v: \"1.0.0\"}}\n"+
			"retract: [\"1.0.9\"]\nmoved: \"corp.example/schemas/svc\"\n"))
	if 0 != code {
		t.Fatalf("manifest = %d:\n%s", code, out)
	}
	for _, want := range []string{
		"verdict: ok",
		"corp.example/schemas/service 1.1.0 public",
		"archive: sha256:",
		"module: corp.example/schemas/service service.aontu aon1-",
		"dep: alias:old 1.0.0 (corp.example/core)",
		"retract: 1.0.9",
		"moved: corp.example/schemas/svc",
		"file: service.aontu sha256:",
	} {
		if !strings.Contains(out, want) {
			t.Fatalf("manifest text lacks %q:\n%s", want, out)
		}
	}

	// A package that declares no version has nothing to publish under,
	// and that is an error class rather than a missing fetch.
	miss, _, code := pkgRun("manifest", pub("", pkgToolSource, ""))
	if 4 != code || !strings.Contains(miss, "pkg.version: missing") {
		t.Fatalf("no version = %d:\n%s", code, miss)
	}

	bad := pub("1.1.0", pkgToolSource, "")
	pkgWrite(t, filepath.Join(bad, "build.sh"), "echo\n")
	if out, _, code := pkgRun("manifest", bad); 4 != code ||
		!strings.Contains(out, "build.sh: not admitted in a package") {
		t.Fatalf("forbidden = %d:\n%s", code, out)
	}

	// The gate's exit class is Subsume's, because the gate IS a
	// subsumption check.
	prior := pub("1.0.0", pkgToolSource, "")
	next := pub("1.1.0", pkgToolSource+"region: *\"eu\" | string\n", "")
	gated, _, code := pkgRun("manifest", "--against", prior, next)
	if 1 != code || !strings.Contains(gated, "verdict: breaking") ||
		!strings.Contains(gated, "$.region: ") {
		t.Fatalf("gate = %d:\n%s", code, gated)
	}

	undecided, _, code := pkgRun("manifest",
		"--against", pub("1.0.0", "a: min(1)\n", ""),
		pub("1.1.0", "a: must(min(1), \"m\")\n", ""))
	if 3 != code || !strings.Contains(undecided, "verdict: undecided") {
		t.Fatalf("undecided gate = %d:\n%s", code, undecided)
	}

	jsonOut, _, code := pkgRun("manifest", "--format", "json",
		pub("1.1.0", pkgToolSource, ""))
	if 0 != code {
		t.Fatalf("manifest json = %d:\n%s", code, jsonOut)
	}
	var report struct {
		Aontu struct {
			Verb string `json:"verb"`
		} `json:"aontu"`
		Manifest struct {
			Modules []struct {
				Canon string `json:"canon"`
			} `json:"modules"`
		} `json:"manifest"`
		Verdict string `json:"verdict"`
	}
	if err := json.Unmarshal([]byte(jsonOut), &report); nil != err {
		t.Fatalf("json: %v\n%s", err, jsonOut)
	}
	if "pkg manifest" != report.Aontu.Verb || "ok" != report.Verdict ||
		1 != len(report.Manifest.Modules) ||
		!strings.HasPrefix(report.Manifest.Modules[0].Canon, "aon1-") {
		t.Fatalf("report %+v", report)
	}
}

