// The rows of test/spec/subsume.tsv as the definition's terms, read by
// defterm.cjs, for the oracle's `subsumerows` cases. A row whose
// documents hold a construct the definition has no term for, or read
// host variables, is left out.
//
//   node ts/scripts/subsume-rows.cjs      writes spec/Oracle/SubsumeRowCases.lean

const Fs = require('node:fs')
const Path = require('node:path')
const { doc, Unsupported, PRELUDE } = require('./defterm.cjs')

const ROOT = Path.join(__dirname, '..', '..')
const ROWS = Path.join(ROOT, 'test', 'spec', 'subsume.tsv')
const OUT = Path.join(ROOT, 'spec', 'Oracle', 'SubsumeRowCases.lean')

const unesc = (t) => t.replace(/\\(.)/g, (_, c) => 'n' === c ? '\n' : 't' === c ? '\t' : c)

function cases(text) {
  const out = []
  for (const line of text.split('\n')) {
    const c = line.split('\t')
    if (line.startsWith('#') || c.length < 5 || 'subsume' !== c[1]) continue
    const opts = JSON.parse(unesc(c[4])).opts ?? {}
    if (Object.keys(opts).some((k) => 'profile' !== k)) continue
    let g, s
    try {
      g = doc(unesc(c[2]))
      s = doc(unesc(c[3]))
    }
    catch (e) {
      if (e instanceof Unsupported) continue
      throw e
    }
    if (g.vars || s.vars) continue
    out.push(`  (${JSON.stringify(c[0])}, .${opts.profile ?? 'defaults'},\n` +
      `    (${g.decls}, ${g.term}),\n    (${s.decls}, ${s.term}))`)
  }
  return 'import Oracle.Base\n\n' +
    '/-! Generated by `ts/scripts/subsume-rows.cjs` from `test/spec/subsume.tsv`:\n' +
    'each row\'s two documents, as the definition\'s terms, where it reads them. -/\n\n' +
    'namespace SubsumeRowCases\n\n' + PRELUDE + '\n' +
    'def cases : List (String × Profile × (Decls × Val) × (Decls × Val)) := [\n' +
    out.join(',\n') + ']\n\nend SubsumeRowCases\n'
}

function generated() {
  return cases(Fs.readFileSync(ROWS, 'utf8'))
}

module.exports = { generated, OUT }

if (require.main === module) {
  Fs.writeFileSync(OUT, generated())
}
